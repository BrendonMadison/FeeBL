#pragma once

#include "gpgeom/phase_space.hpp"

#include <array>
#include <cstddef>
#include <functional>
#include <stdexcept>
#include <vector>

namespace gpgeom {

struct Harmonic {
  int n{1};
  double amplitude{};  // normalized transverse momentum kick
  double phase{};      // rad
};

class CrabRFCavityMap {
 public:
  CrabRFCavityMap(double wave_number_per_m, std::vector<Harmonic> harmonics);

  void apply(PhaseSpace6D& p) const noexcept;
  [[nodiscard]] double kick(double zeta) const noexcept;
  [[nodiscard]] double kick_derivative(double zeta) const noexcept;

  // Return amplitudes A_1 and A_n for K(z)=A_1 sin(kz)+A_n sin(nkz),
  // with K'(0)=target_slope and K'''(0)=0.
  [[nodiscard]] static std::array<double, 2> cubic_linearizer(
      double target_slope_per_m, double wave_number_per_m, int harmonic_n);

 private:
  double k_{};
  std::vector<Harmonic> harmonics_;
};

class CrabWaistMap {
 public:
  // The exact local map is generated by S_2 = q.P + 1/2 g(x) P_y^2.
  // For the ideal map, g(x)=-fraction*x/tan(full_crossing_angle).
  CrabWaistMap(double full_crossing_angle_rad, double fraction,
               double cubic_coefficient_per_m2 = 0.0);

  void apply(PhaseSpace6D& p) const noexcept;
  [[nodiscard]] double g(double x) const noexcept;
  [[nodiscard]] double dg_dx(double x) const noexcept;

 private:
  double linear_coefficient_{};
  double cubic_coefficient_{};
};

class AffineMap6D {
 public:
  AffineMap6D(Matrix6 matrix, std::array<double, 6> offset);
  void apply(PhaseSpace6D& p) const noexcept;
  [[nodiscard]] const Matrix6& matrix() const noexcept { return matrix_; }

 private:
  Matrix6 matrix_{};
  std::array<double, 6> offset_{};
};

using MapFunction = std::function<void(PhaseSpace6D&)>;

[[nodiscard]] Matrix6 numerical_jacobian(const MapFunction& map,
                                         const PhaseSpace6D& around,
                                         double step = 1.0e-7);

[[nodiscard]] double symplectic_defect_inf_norm(const Matrix6& jacobian) noexcept;

}  // namespace gpgeom
