#ifndef FEEBL_IMPORTED_SPIN_CPP_H
#define FEEBL_IMPORTED_SPIN_CPP_H

#include "particlesCPP.h"
#include <fstream>
#include <iomanip>
#include <map>
#include <sstream>
#include <stdexcept>

namespace feebl { namespace imported_spin {

// This independent identity ledger is not limited by the GUI's display cap.
// Source ordinals bind initial and final state before any tracking reordering.
class Registry {
  struct Initial {
    std::size_t source_record;
    int scheduled,admitted;
    std::string state;
  };
  std::map<int,Initial> initial_;

  static void write_state(std::ostream& out,const PAIR_PARTICLE& p) {
    float x,y,vx,vy;p.XYposition(x,y);p.velocities(vx,vy);
    const auto& spin=p.getSpin();
    const double values[]={p.signed_energy(),x,y,p.z(),vx,vy,p.Zvelocity(),
                           spin(0),spin(1),spin(2),p.imported_helicity()};
    for (const double value:values)
      if (!std::isfinite(value)) throw std::runtime_error("Nonfinite imported spin state");
    out << "{\"signed_energy_GeV\":" << p.signed_energy()
        << ",\"position_nm\":[" << x << ',' << y << ',' << p.z()
        << "],\"beta\":[" << vx << ',' << vy << ',' << p.Zvelocity()
        << "],\"spin\":[" << spin(0) << ',' << spin(1) << ',' << spin(2)
        << "],\"helicity\":" << p.imported_helicity() << '}';
  }
public:
  void add(const PAIR_PARTICLE& p,std::size_t source,int scheduled,int admitted) {
    if (initial_.size()>=131072)
      throw std::length_error("Imported spin identity limit is 131072 tracks");
    std::ostringstream state;state << std::setprecision(17);write_state(state,p);
    if (!initial_.emplace(p.get_label(),Initial{source,scheduled,admitted,state.str()}).second)
      throw std::logic_error("Duplicate imported spin label");
  }

  template<class Range> void write(const char* path,const Range& particles) const {
    std::map<int,const PAIR_PARTICLE*> final;
    for (const auto& p:particles)
      if (!final.emplace(p.get_label(),&p).second)
        throw std::logic_error("Duplicate final imported spin label");
    if (final.size()!=initial_.size()) throw std::logic_error("Imported spin population does not close");
    for (const auto& initial:initial_)
      if (!final.count(initial.first)) throw std::logic_error("Missing final imported spin label");
    std::ofstream out(path);
    if (!out) throw std::runtime_error("Cannot open imported spin output");
    out << std::setprecision(17)
        << "{\"schema_version\":\"feebl.imported-spin/1\",\"mode\":1,"
        << "\"transport\":\"finite-mass Thomas-BMT; symmetric E/B substeps; exact magnetic orbit rotation\","
        << "\"anomalous_moment\":\"BformFunction(chi) evaluated using combined gathered E and cB\","
        << "\"radiation\":\"disabled for imported spin tracks\",\"radiative_spin_flips\":false,"
        << "\"primary_beam_radiation\":\"independently controlled by input card\","
        << "\"spin_definition\":\"rest-frame polarization components on fixed native laboratory axes\","
        << "\"helicity_definition\":\"S dot beta/|beta|\","
        << "\"signed_energy_convention\":\"positive electron; negative positron\","
        << "\"force_convention\":\"q_eff=sign(signed_energy); field_pair supplies charge-weighted E and cB\","
        << "\"max_chi_definition\":\"maximum over spin substep evaluations; not a continuous-time maximum\","
        << "\"hard_scattering_spin_correlations\":\"not generated by this transport mode\","
        << "\"electron_mass_GeV\":" << EMASS << ",\"tracks\":[";
    bool first=true;
    for (const auto& entry:initial_) {
      const auto& initial=entry.second;const auto& p=*final.at(entry.first);
      if (!first) {
        out << ',';
      }
      first=false;
      out << "{\"label\":" << entry.first << ",\"source_record\":" << initial.source_record
          << ",\"scheduled_time_counter\":" << initial.scheduled
          << ",\"admitted_time_counter\":" << initial.admitted
          << ",\"pdg_id\":" << (p.signed_energy()>0 ? 11 : -11)
          << ",\"initial\":" << initial.state << ",\"final\":";
      write_state(out,p);
      out << ",\"max_chi\":" << p.imported_max_chi()
          << ",\"field_intervals\":" << p.imported_spin_steps()
          << ",\"field_gathers\":[" << p.imported_field_gathers(0) << ','
          << p.imported_field_gathers(1) << ',' << p.imported_field_gathers(2) << "]}";
    }
    out << "]}\n";
    if (!out) throw std::runtime_error("Cannot complete imported spin output");
  }
};
} }
#endif
