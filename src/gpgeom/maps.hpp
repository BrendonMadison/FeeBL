// IP DISPERSION, the map monochromatization is built from.
//
// Giving the two beams OPPOSITE dispersion at the IP correlates a particle's
// energy with its transverse position, so the pairs that actually meet are
// those whose energies sum near a common value. The invariant-mass spread
// narrows without the beam energy spread changing at all.
//
// Exactly symplectic, being the Lie map of G = D * delta * px:
//
//     dx/ds    =  dG/dpx    =  D * delta      ->  x    += D * delta
//     dpx/ds   = -dG/dx     =  0
//     dzeta/ds =  dG/ddelta =  D * px         ->  zeta += D * px
//     ddelta/ds= -dG/dzeta  =  0
//
// The zeta term is the companion, and it is not optional: dropping it gives a
// map that moves particles transversely for free and quietly violates Liouville,
// exactly as dropping the Panofsky-Wenzel term would for the crab.
//
// Structurally identical to the crab IP tilt, which is the Lie map of
// G = t * zeta * px. The difference is which conjugate variable drives the
// shear -- zeta there, delta here.
//
// The sign of D is per beam and is not optional: opposite dispersion is what
// narrows the spectrum, and the same sign on both beams broadens it.
class IPDispersionMap {
 public:
  // dispersion_m is D in metres per unit relative energy deviation.
  // vertical selects the (y, py) plane instead of (x, px).
  explicit IPDispersionMap(double dispersion_m, bool vertical = false);
  void apply(PhaseSpace6D& p) const noexcept;
  // The exact inverse, so a chain can be composed and undone. Same map with
  // -D, which is its own proof: the generator is linear in D.
  void apply_inverse(PhaseSpace6D& p) const noexcept;
  [[nodiscard]] double dispersion() const noexcept { return d_; }
  [[nodiscard]] bool vertical() const noexcept { return vertical_; }

 private:
  double d_;
  bool vertical_;
};

