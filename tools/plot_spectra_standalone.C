// plot_spectra_standalone.C -- luminosity spectra, data included.
//
// A self-contained version of tools/plot_spectra.C: every bin content and bin
// edge is embedded below, so this file needs no input data at all.
//
//   root -l -b -q 'plot_spectra_standalone.C'
//   root -l -b -q 'plot_spectra_standalone.C("ILC250")'
//
// Writes a PDF, a PNG and a .root holding the six TH1F objects per machine.
//
// WHAT THE HISTOGRAMS ARE.  FEEBL beam-beam simulations of IP-dispersion
// monochromatization at three machines, each with no dispersion ("base") and
// with co-optimised monochromatization ("mono") -- beta*_x squeezed and IP
// dispersion refilling the horizontal width, holding sigma_x,tot and therefore
// the geometric luminosity fixed.
//
// Each entry is one stored colliding pair, sampled so that every pair carries
// EQUAL luminosity weight. An unweighted histogram of them is therefore the
// luminosity spectrum, and the bin contents below are raw pair counts from the
// full per-pair output -- not downsampled, not reweighted.
//
// sqrt(s) is the exact invariant mass, W^2 = 2m^2 + 2(E1E2 - p1.p2), with
// |p| formed as sqrt((E-m)(E+m)) so it does not lose the difference to
// cancellation.
//
// WINDOWING.  Each panel spans -7 sigma to +2.5 sigma about the BASELINE peak,
// sigma being the Gaussian-equivalent core width (FWHM/2.3548) of the baseline
// dL/dW. Both curves share an axis, so the narrowing reads as a narrower peak
// in a fixed frame rather than a rescaled axis; the asymmetry keeps a slice of
// the beamstrahlung tail in view without letting it dominate. For the
// single-beam panels sigma_E = sigma_W/sqrt(2), exact for W = E1+E2 with
// independent beams.
//
// A CAVEAT CARRIED FROM THE SOURCE FILES.  Momenta were in the HEAD-ON frame:
// FEEBL applies the crossing angle as a per-slice position shear only, so
// directions are short by the half crossing angle. Energy-domain quantities --
// all that is plotted here -- are valid; angular ones are not.
//
// A CAVEAT ON THE NUMBERS.  No grid is converged and n_m is pinned at 200000,
// so absolute luminosities run about 76% of design. Shapes and ratios are
// trustworthy; absolute normalisation is indicative.
//
// Generated from studies/FINDINGS.md's six configurations. See that document
// for the parameter table and the physics.

